def 접기(줄: str) -> str:
    """.ics 는 한 줄이 75옥텟을 넘으면 접어야 한다.

    🔴 옥텟으로 자르면 **한글 한 글자가 반으로 갈린다.** 그래서 글자 단위로 넣으면서
    바이트 수를 재고, 넘기 직전에 접는다(이어지는 줄은 공백 한 칸으로 시작한다).
    """
    나온줄, 현재, 한도 = [], "", 73
    for 글자 in 줄:
        if len((현재 + 글자).encode()) > 한도:
            나온줄.append(현재)
            현재, 한도 = " " + 글자, 74  # 이어지는 줄은 앞 공백 1칸을 포함해서 센다
        else:
            현재 += 글자
    나온줄.append(현재)
    return "\r\n".join(나온줄)


def 피하기(값: str) -> str:
    """텍스트 값의 예약문자. 순서가 중요하다 — 역슬래시를 먼저 바꾼다."""
    return (
        값.replace("\\", "\\\\")
        .replace(";", "\\;")
        .replace(",", "\\,")
        .replace("\n", "\\n")
    )


def 굽기(올린날: dt.date, 추정인가: bool) -> str:
    찍은시각 = dt.datetime.now(dt.timezone.utc).strftime("%Y%m%dT%H%M%SZ")
    줄 = [
        "BEGIN:VCALENDAR",
        "VERSION:2.0",
        "PRODID:-//CatchFlower//release schedule//KO",
        "CALSCALE:GREGORIAN",
        "METHOD:PUBLISH",
        f"X-WR-CALNAME:{피하기('캐치플라워 출시 일정' + (' (올린날 추정)' if 추정인가 else ''))}",
    ]
    for 항목 in 일정들(올린날):
        끝 = 항목["시작"] + dt.timedelta(days=항목["일수"])
        제목 = 항목["제목"] + (" · 올린날 추정" if 추정인가 else "")
        줄 += [
            "BEGIN:VEVENT",
            f"UID:{항목['이름']}@catchflower.app",
            f"DTSTAMP:{찍은시각}",
            "SEQUENCE:0",
            f"DTSTART;VALUE=DATE:{항목['시작']:%Y%m%d}",
            f"DTEND;VALUE=DATE:{끝:%Y%m%d}",
            f"SUMMARY:{피하기(제목)}",
            f"DESCRIPTION:{피하기(항목['설명'])}",
            "TRANSP:TRANSPARENT",
        ]
        if 항목.get("반복"):
            줄.append(f"RRULE:{항목['반복']}")
        for 며칠전 in 항목["알림"]:
            # 종일 일정의 알림은 시작 자정 기준이다. 09:00에 울리게 9시간을 더한다.
            시간 = 며칠전 * 24 + 9
            표기 = f"{'-' if 시간 < 0 else ''}PT{abs(시간)}H"
            줄 += [
                "BEGIN:VALARM",
                "ACTION:DISPLAY",
                f"TRIGGER;RELATED=START:{표기}",
                f"DESCRIPTION:{피하기(항목['제목'])}",
                "END:VALARM",
            ]
        줄.append("END:VEVENT")
    줄.append("END:VCALENDAR")
    # 🔴 접기는 **마지막에 전 줄에** 건다. 만드는 자리마다 부르면 반드시 빠뜨린다 —
    #    처음 판은 SUMMARY·DESCRIPTION만 접고 **알림 안의 DESCRIPTION을 놓쳐서** 4줄이
    #    75옥텟을 넘었다(검사가 알려줬다).
    접힌줄 = [접기(하나) for 하나 in 줄]

    # 규격을 스스로 잰다. 캘린더는 긴 줄을 **조용히 잘라 버리므로** 파일이 열리는 것으로는
    # 확인이 안 된다(설명 뒷부분만 사라진다). 넘으면 파일을 쓰지 않고 멈춘다.
    넘는줄 = [하나 for 묶음 in 접힌줄 for 하나 in 묶음.split("\r\n") if len(하나.encode()) > 75]
    if 넘는줄:
        raise AssertionError(f"75옥텟을 넘는 줄 {len(넘는줄)}개: {넘는줄[0][:60]}…")

    return "\r\n".join(접힌줄) + "\r\n"


def main() -> int:
    받기 = argparse.ArgumentParser(description="출시 일정을 .ics로 굽는다")
    받기.add_argument(
        "--올린날",
        help="클로즈드 테스트 트랙에 올린 날 (YYYY-MM-DD). 안 주면 오늘로 잡고 「추정」을 붙인다",
    )
    받기.add_argument("--출력", default=str(기본_출력))
    받기.add_argument("--보기만", action="store_true", help="파일을 쓰지 않고 날짜만 찍는다")
    인자 = 받기.parse_args()

    추정인가 = 인자.올린날 is None
    if 추정인가:
        올린날 = dt.date.today()
        print("⚠️ --올린날 을 안 줬다 — 오늘로 잡았다. 실제로 올린 날로 다시 구워라.")
    else:
        try:
            올린날 = dt.date.fromisoformat(인자.올린날)
        except ValueError:
            print(f"🔴 날짜 형식이 아니다: {인자.올린날} (YYYY-MM-DD)", file=sys.stderr)
            return 1

    for 항목 in 일정들(올린날):
        끝 = 항목["시작"] + dt.timedelta(days=항목["일수"]) - dt.timedelta(days=1)
        기간 = f"{항목['시작']}" if 항목["일수"] == 1 else f"{항목['시작']} ~ {끝}"
        print(f"  {기간:<26} {항목['제목']}")

    if 인자.보기만:
        return 0

    글 = 굽기(올린날, 추정인가)
    낼곳 = pathlib.Path(인자.출력).expanduser()
    낼곳.write_text(글, encoding="utf-8", newline="")
    print(f"\n🔵 {len(일정들(올린날))}개 일정을 썼다 → {낼곳} ({len(글.encode())}바이트)")
    print("   파일을 열면(더블클릭) 캘린더가 받는다. 어느 캘린더에 넣을지는 그때 고른다.")
