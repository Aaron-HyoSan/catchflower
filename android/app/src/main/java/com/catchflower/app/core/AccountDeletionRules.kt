package com.catchflower.app.core

/**
 * 회원 탈퇴의 **순서와 판정**. 화면 20-2 8행(A 문서 3절 ⑪).
 *
 * 2026-08-16에 출시 준비로 생겼다. Play 정책은 **계정을 만드는 앱에 앱 안 삭제 경로**를
 * 요구한다 — 우리는 첫 실행에 익명 계정을 만들므로 해당된다.
 *
 * ## 🔴 왜 규칙을 화면·서비스가 아니라 여기 두는가
 *
 * 이 기능의 결함은 **전부 조용하다.**
 *
 * 1. **순서가 틀리면** 지워진 것과 안 지워진 것이 섞이는데 화면은 똑같이 "탈퇴됨"이다.
 * 2. **실패한 뒤 기기를 지우면** 사용자는 탈퇴됐다고 믿고, 서버에는 계정·기록이 남고,
 *    **다시 시도할 방법이 없다**(로컬 토큰이 없으니 그 계정으로 로그인할 수 없다).
 *    이게 이 기능에서 가장 나쁜 결과이고, 성공 화면과 구별되지 않는다.
 * 3. **프로필을 먼저 지우면** 중간에 끊겼을 때 남의 화면에 `탈퇴한 사용자예요`로
 *    보이면서 발견 기록·지도 핀은 그대로 남는다.
 */
object AccountDeletionRules {

    /**
     * 서버에서 지우는 순서. **[entries] 순서가 그대로 실행 순서다.**
     *
     * 🔴 [DISCOVERIES]가 맨 앞이다 — `discoveries`를 지우면 `on delete cascade`로
     *    **내 사진에 달린 남의 댓글·좋아요가 같이** 사라진다(0007). 뒤로 밀면 그 사이에
     *    실패했을 때 "주인 없는 댓글"이 남는다.
     *
     * 🔴 [PROFILE]이 맨 끝이다 — 이건 유일한 **soft delete**이고(`users`에 delete
     *    정책이 없다) 성공하는 순간 `public_profiles`에서 사라져 남들에게
     *    `탈퇴한 사용자예요`가 된다. 그 앞의 것이 아직 남아 있으면 **이름만 지워진
     *    유령 계정**이 되고, 그 상태는 화면으로 알 수 없다.
     */
    enum class Step(val what: String) {
        /** `DELETE discoveries?user_id=eq.me` — 댓글·좋아요가 cascade로 함께 지워진다. */
        DISCOVERIES("발견 기록"),

        /** `DELETE likes?user_id=eq.me` — **남의 사진에 누른** 좋아요. */
        LIKES("좋아요"),

        /** `DELETE friendships?or(requester_id,addressee_id)` — 양쪽 다 지울 수 있다. */
        FRIENDSHIPS("친구 관계"),

        /** `DELETE blocks?blocker_id=eq.me` — 내가 차단한 목록. */
        BLOCKS("차단 목록"),

        /**
         * `PATCH users?id=eq.me` — `deleted_at`과 닉네임·활동 지역을 비운다.
         *
         * ⚠️ **행을 지우지 않는다.** `users`에 delete 정책이 없고(0001 7-2),
         *    만들면 `discoveries.user_id`가 cascade로 걸려 있어 서버 작업이 커진다.
         *    개인정보 처리방침 6항이 약속한 것은 "즉시 지운다"가 아니라 이 목록이다.
         */
        PROFILE("프로필"),
    }

    /**
     * 서버 단계가 **하나라도** 실패했으면 기기를 지우지 않는다.
     *
     * 🔴 이 한 줄이 위 ②를 막는다. 반대로 하면(로컬을 먼저·항상 지우면) 화면은 성공과
     *    똑같은데 **되돌릴 수도, 다시 시도할 수도 없는** 상태가 된다.
     *
     * ⚠️ 그래서 실패 문구는 `아직 아무것도 지워지지 않았어요`가 **아니다** —
     *    서버 단계는 요청 5개라 3번째에서 끊기면 앞의 둘은 이미 지워졌다(A 문서 3절 ⑪).
     */
    fun mayWipeDevice(failed: Step?): Boolean = failed == null

    /**
     * 다이얼로그가 있을 수 있는 상태. **문구는 A 문서 3절 ⑪이 전부다.**
     *
     * ⚠️ [Done]에서 자동으로 앱을 재시작하지 않는다 — 결과를 읽을 시간이 필요하고,
     *    토스트로 대신하면 재시작에 묻혀 **아무 말도 안 한 것과 같아진다**.
     */
    sealed interface Phase {
        /** `정말 탈퇴할까요?` */
        data object Confirm : Phase

        /** `탈퇴를 처리하고 있어요` — 이 동안 버튼을 다시 누를 수 없어야 한다. */
        data object Running : Phase

        /** `탈퇴가 끝났어요` + `확인`. 누르면 앱을 처음 상태로 되돌린다. */
        data object Done : Phase

        /**
         * `탈퇴를 마치지 못했어요` + `다시 시도`.
         *
         * @param failedAt 어디서 끊겼는지. **화면에 쓰지 않는다**(사용자가 할 수 있는
         *   일이 달라지지 않는다) — 로그에만 남긴다.
         */
        data class Failed(val failedAt: Step?) : Phase
    }

    /**
     * 다시 시도할 때 **처음부터** 다시 돌린다.
     *
     * 🔴 실패한 단계부터 이어서 하지 않는다. 필터가 붙은 DELETE는 여러 번 불러도 결과가
     *    같고(이미 없으면 0행이다), 반대로 "이어서"를 구현하면 앱이 죽거나 사용자가
     *    나갔다 온 뒤에 **어디까지 했는지 모르는 상태**가 생긴다 — 그걸 저장하면
     *    "탈퇴 중" 상태를 기기에 남기는 것이고, 그 상태로 앱을 쓰면 화면이 거짓말을 한다.
     */
    const val RETRY_FROM_START = true
}
