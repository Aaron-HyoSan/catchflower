/**
 * Compose **밖에서** 토스트를 띄운다 — 지금 부르는 곳은
 * [com.catchflower.app.AuthCallbackActivity] 하나다.
 *
 * ## 왜 필요했나
 *
 * 로그인 콜백은 **Compose가 없는 액티비티**에서 끝난다(`Theme.NoDisplay` · `finish()`).
 * [rememberToaster]는 `@Composable`이라 거기서 못 쓴다.
 *
 * 🔴 **결과를 MainActivity로 넘겨서 띄우는 배선을 만들지 않았다.** 그러면 "콜백은
 *    왔는데 토스트가 안 뜬다"는 상태가 생기고(플래그를 읽는 시점과 화면 재생성이
 *    엇갈린다), 그건 **로그인이 실패한 것과 화면이 똑같다** — 지금 고치는 문제가
 *    바로 그것이다. 토스트는 시스템 창이라 액티비티가 끝나도 뜬다.
 *
 * ⚠️ **`LENGTH_LONG`이다**([rememberToaster]는 SHORT). 사용자는 브라우저에서 앱으로
 *    돌아오는 중이고 그 사이 화면이 두 번 바뀐다 — SHORT면 전환에 묻힌다.
 */
fun showToastNow(context: android.content.Context, toast: CfToast) {
    android.widget.Toast
        .makeText(context, toast.message, android.widget.Toast.LENGTH_LONG)
        .show()
}

/**
 * 토스트를 띄운다. 부르는 쪽이 `Toast.makeText(...).show()`를 매번 쓰지 않게 한다.
 *
 * ⚠️ **`LENGTH_SHORT`다.** [CfToast.NOT_READY]는 누를 때마다 뜨는데, 길게 두면
 *    연달아 눌렀을 때 큐에 쌓여 다른 화면에서까지 뜬다.
 */
@androidx.compose.runtime.Composable
fun rememberToaster(): (CfToast) -> Unit {
    val context = androidx.compose.ui.platform.LocalContext.current
    return { toast ->
        android.widget.Toast
            .makeText(context, toast.message, android.widget.Toast.LENGTH_SHORT)
            .show()
    }
}
