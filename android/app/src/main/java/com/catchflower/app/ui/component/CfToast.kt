package com.catchflower.app.ui.component

/**
 * 토스트 문구. **원본은 `디자이너_업무/A_문구·버튼_스펙.md` 3절 "토스트" 표다.**
 *
 * ⚠️ **여기서 새 문구를 만들지 않는다.** 필요한 문구가 없으면 A 문서에 먼저 추가하고
 *    `진행.md`에 남긴 다음 여기에 넣는다. 개발자가 지어낸 말투는 40~50대 대상 톤 검토를
 *    거치지 않은 것이다.
 *
 * 표에는 7개가 있지만 **지금 쓰는 것만 넣는다** — 안 쓰는 상수는 "구현됐다"고 착각하게 만든다.
 */
enum class CfToast(val message: String) {

    /**
     * A 문서 3절: `네트워크 오류 | 연결이 불안정해요. 잠시 후 다시 시도해 주세요.`
     *
     * PlantNet 호출 실패·일일 한도 초과에 함께 쓴다. 사용자가 할 수 있는 게
     * "잠시 후 다시"인 건 같고, **한도 전용 문구는 A 문서에 없다.**
     */
    NETWORK_ERROR("연결이 불안정해요. 잠시 후 다시 시도해 주세요."),

    /**
     * A 문서 3절: `도감 등록 후 공유 안 함 | 도감에는 저장됐어요`
     *
     * 화면 13의 `공유하지 않기`가 쓴다. **꼭 필요한 문구다** — 그 버튼을 누르면
     * 아무 일도 안 일어난 것처럼 보이는데(공개 범위가 이미 `private`이라 바뀌는 게 없다),
     * 사용자는 방금 찍은 꽃이 어디로 갔는지 알 수 없다.
     */
    DEX_SAVED_ONLY("도감에는 저장됐어요"),

    /** A 문서 3절: `지도 공유 완료 | 지도에 공유했어요` — 화면 13의 `공유하기`. */
    MAP_SHARED("지도에 공유했어요"),

    /**
     * A 문서 3절 `아직 안 만든 기능을 눌렀을 때`: `예선 범위 밖 기능 | 아직 준비 중이에요`
     *
     * 🔴 **예선 범위에서 버튼 10개가 눌려도 아무 일도 안 했다**(2026-08-09 · (38)).
     *    코드에는 `TODO`가 달려 있었지만 **화면에는 아무 표시가 없어서** 누른 사람은
     *    앱이 고장난 것으로 읽는다. 시연에서 눌리는 것이 대부분 그 버튼들이다.
     *
     * ⚠️ **이 토스트가 뜨는 것은 기능이 아니다.** 기능이 없다는 안내이므로
     *    `구현현황_AOS.md`에 ✅를 주지 않는다.
     */
    NOT_READY("아직 준비 중이에요"),

    /**
     * A 문서 3절: `신고 접수 | 신고를 접수했어요. 확인 후 처리됩니다.` — 화면 16 헤더 `신고`.
     *
     * 🔴 **이 토스트가 유일한 결과 표시다.** 서버 정책 `reports_read_own`은 본인 신고만
     *    돌려주고, 자동 숨김은 신고 3건이 모여야 도는 서버 판정이다 — 즉 **신고한
     *    화면은 신고 전과 완전히 똑같다.** 토스트를 빼면 눌린 것인지 실패한 것인지
     *    알 방법이 없어서 사용자는 같은 기록을 여러 번 신고한다.
     *
     * ⚠️ 실패에는 [NETWORK_ERROR]를 쓴다. 접수 안 된 것을 접수됐다고 말하면
     *    **신고가 사라진 것을 아무도 모른다.**
     */
    REPORT_RECEIVED("신고를 접수했어요. 확인 후 처리됩니다."),

    /**
     * A 문서 3절 `화면 16 댓글 삭제` 표: `삭제 성공 | 댓글을 지웠어요`
     *
     * ⚠️ **낙관적으로 먼저 띄우지 않는다.** 서버 `delete_comment`는 **실패도 HTTP 200**에
     *    본문 `false`로 오므로(0009), 누른 즉시 이걸 띄우면 **안 지워진 댓글에
     *    "지웠어요"가 뜬다.** 응답을 받은 뒤에만 띄운다.
     */
    COMMENT_DELETED("댓글을 지웠어요"),

    /**
     * A 문서 3절 `화면 16 댓글 삭제` 표: `삭제 실패 | 댓글을 지우지 못했어요`
     *
     * 🔴 **여기에 [NETWORK_ERROR]를 쓰지 않는다.** 서버가 주는 `false`는 권한 없음·없는
     *    id·미로그인을 **일부러 구분해 주지 않는데**(남의 댓글이 존재하는지 알려 주지
     *    않으려는 설계다 · 0009), 그중 몇은 **다시 시도해도 결과가 같다.**
     *    `잠시 후 다시 시도해 주세요`는 그 경우에 **틀린 안내**가 된다
     *    (화면 01 `manual_linking_disabled`에서 같은 판단을 했다).
     *
     * ⚠️ 반대로 **네트워크가 실제로 끊긴 경우**(HTTP 0·5xx)는 [NETWORK_ERROR]다.
     *    두 갈래를 [com.catchflower.app.ui.place.RecordRules.deleteToastIsNetwork]가
     *    응답 코드로 나눈다 — 화면에서 `if`로 나누면 판정이 검증 밖에 남는다.
     */
    COMMENT_DELETE_FAILED("댓글을 지우지 못했어요"),
}

/**
 * 토스트를 띄운다. 부르는 쪽이 `Toast.makeText(...).show()`를 매번 쓰지 않게 한다.
 *
 * ⚠️ **`LENGTH_SHORT`다.** [CfToast.NOT_READY]는 누를 때마다 뜨는데, 길게 두면
 *    연달아 눌렀을 때 큐에 쌓여 다른 화면에서까지 뜬다.
 */
@androidx.compose.runtime.Composable
fun rememberToaster(): (CfToast) -> Unit {
    val context = androidx.compose.ui.platform.LocalContext.current
    return { toast ->
        android.widget.Toast
            .makeText(context, toast.message, android.widget.Toast.LENGTH_SHORT)
            .show()
    }
}
