-- ════════════════════════════════════════════════════════════════
--  03 — 개발 중 만든 **익명 테스트 계정**을 지운다
-- ════════════════════════════════════════════════════════════════
--
--  🔴 **왜 uuid 목록이 아니라 조회인가.** 나는 회차마다 익명 계정을 만들어 실서버로
--     검증했다(RLS·랭킹·좋아요·댓글·카카오 연결). 그 uuid들은 **내 도구 출력에만**
--     남아 있고 파일로 모아 둔 적이 없다.
--
--     🔵 오너에게 "15개 새로 만들었다 → 누적 28개"라고 보고한 적이 있다.
--        **그 숫자는 셈이 아니라 어림이다.** 중간에 죽은 스크립트도 계정을 이미
--        만든 뒤에 죽었고(`ai_confidence` 누락 · 하루중복 409), 그것까지 세지 않았다.
--        손으로 옮겨 적은 목록을 주면 **빠진 계정이 영구히 남는다** — 그리고
--        "정리했다"는 기록만 남아서 아무도 다시 안 본다(`제출 문서 수치는 틀린다`).
--
--     → 그래서 **서버가 스스로 세게 한다.** 아래 1절이 목록을 만들고, 오너가 그걸
--       보고 2절을 돌린다.
--
--  🔴 **`a31bcf09-…`은 지우지 않는다** (오너 지시). ⚠️ **전체 uuid를 나는 모른다** —
--     기록에 앞 8자리만 남아 있다. 그래서 **접두사로 고른다**(`id::text like 'a31bcf09%'`).
--     ⚠️ 처음에 `'a31bcf09-0000-0000-0000-000000000000'`으로 적었는데 **그건 내가
--     지어낸 값**이다. 그렇게 두면 `<>` 비교가 **항상 참**이 되어 보존 계정이
--     조용히 삭제 대상에 들어간다 — 오류도 안 나고, 지운 뒤에야 안다.
--
--  ⚠️ **1절만 먼저 돌린다.** 2절은 되돌릴 수 없다.


-- ─────────────────────────────────────────────────────────────
-- 1. 먼저 **세어 본다.** (지우지 않는다)
-- ─────────────────────────────────────────────────────────────
--
-- ⚠️ **`is_anonymous`로만 고르지 않는다.** 오너가 직접 익명으로 앱을 켜 본 계정도
--    같은 표시를 달고 있고, 그 계정에는 **오너의 실물 꽃 기록**이 들어 있을 수 있다
--    (실기기 QA를 했다). 그래서 **기록이 하나도 없는 것**만 후보로 둔다.
select
  u.id,
  u.created_at,
  u.is_anonymous,
  (select count(*) from public.discoveries d where d.user_id = u.id) as 발견기록,
  (select count(*) from public.comments   c where c.user_id = u.id) as 댓글,
  (select count(*) from public.likes      l where l.user_id = u.id) as 좋아요,
  case
    when u.id::text like 'a31bcf09%' then '🔒 오너 지시로 보존'
    when (select count(*) from public.discoveries d where d.user_id = u.id) > 0
      then '⚠️ 기록이 있다 — 지우기 전에 확인'
    else '🧹 정리 후보'
  end as 판정
from auth.users u
where u.is_anonymous is true
order by u.created_at;

-- ⚠️ 위 결과에서 `발견기록 > 0`인 줄이 나오면 **거기서 멈추고 알려 준다.**
--    오너의 실기기 QA 기록일 수 있고, 그건 지금 유일한 실물 꽃 데이터다.


-- ─────────────────────────────────────────────────────────────
-- 2. 지운다 — **1절을 보고 나서** 돌린다
-- ─────────────────────────────────────────────────────────────
--
-- ⚠️ 🔴 **이 절은 주석으로 막아 두었다.** 1절 결과를 보기 전에 실행되면 안 된다.
--    쓸 때는 `/*` `*/` 를 지운다.
--
-- ⚠️ **`delete from auth.users`가 맞다.** `public.users`만 지우면 GoTrue에 계정이
--    남아서 그 `refresh_token`이 계속 유효하다 — 그 기기는 **지워진 줄 모르고**
--    계속 쓰다가 외래키에서 막힌다. 반대로 `auth.users`를 지우면
--    `public.users`는 `on delete cascade`로 따라간다(0001).
/*
delete from auth.users u
where u.is_anonymous is true
  -- 🔒 오너 지시로 보존
  and u.id::text not like 'a31bcf09%'
  -- 🔴 기록이 있는 계정은 건드리지 않는다 (1절 주석 참고)
  and not exists (select 1 from public.discoveries d where d.user_id = u.id);
*/


-- ─────────────────────────────────────────────────────────────
-- 3. 지운 뒤 확인
-- ─────────────────────────────────────────────────────────────
--
-- ⚠️ **`0`이 나오는 것을 성공으로 읽지 않는다.** 2절을 주석 그대로 두고 돌려도
--    이 줄은 아무 오류 없이 결과를 준다 — "지웠다"와 "안 지웠다"가 같은 모양이다.
--    그래서 **남은 개수와 보존 계정을 같이** 센다.
select
  (select count(*) from auth.users where is_anonymous is true) as 남은_익명계정,
  (select count(*) from auth.users
     where is_anonymous is true
       and exists (select 1 from public.discoveries d where d.user_id = auth.users.id)
  ) as 그중_기록있는것,
  (select count(*) from auth.users where id::text like 'a31bcf09%') as 보존계정_살아있나;
-- ⚠️ `보존계정_살아있나`가 **1이어야** 한다. 0이면 지우지 말아야 할 것을 지웠다는
--    뜻이고, `true/false`가 아니라 **개수로** 받는 이유는 2 이상이면 접두사가
--    여러 계정에 걸린다는 뜻이라 그것도 알아야 하기 때문이다.
