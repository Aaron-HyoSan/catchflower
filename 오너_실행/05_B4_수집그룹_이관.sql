--
--  ## 표 (대표 ⟵ 멤버)
--
--  | 31 민들레 ⟵ 32 서양민들레
--  | 38 별꽃 ⟵ 39 쇠별꽃 · 40 개별꽃
--  | 73 팬지 ⟵ 74 비올라
--  | 102 망초 ⟵ 103 실망초
--  | 105 금계국 ⟵ 104 큰금계국 · 106 기생초
--  | 139 여뀌 ⟵ 140 개여뀌 · 142 이삭여뀌
--  | 161 메리골드 ⟵ 162 만수국
--  | 184 쑥부쟁이 ⟵ 185 개미취 · 186 미국쑥부쟁이 · 187 참취
--
-- ────────────────────────────────────────────────────────────────
--  1절 — 미리보기. **아무것도 바꾸지 않는다.**
-- ────────────────────────────────────────────────────────────────
--  🔵 `고칠행 0`이 나오면 **그것도 정상이다** — 그 멤버로 등록한 사람이 없었다는
--     뜻이다. 0이 나쁜 신호인 것은 `flowers`에 그 번호가 없을 때뿐인데,
--     그건 아래 `종이름`이 비는 것으로 갈린다(비면 나에게 알려 주세요).

with 그룹(멤버, 대표) as (
  values
    (32, 31),   -- 서양민들레 → 민들레
    (39, 38),   -- 쇠별꽃 → 별꽃
    (40, 38),   -- 개별꽃 → 별꽃
    (74, 73),   -- 비올라 → 팬지
    (103, 102),   -- 실망초 → 망초
    (104, 105),   -- 큰금계국 → 금계국
    (106, 105),   -- 기생초 → 금계국
    (140, 139),   -- 개여뀌 → 여뀌
    (142, 139),   -- 이삭여뀌 → 여뀌
    (162, 161),   -- 만수국 → 메리골드
    (185, 184),   -- 개미취 → 쑥부쟁이
    (186, 184),   -- 미국쑥부쟁이 → 쑥부쟁이
    (187, 184)   -- 참취 → 쑥부쟁이
)
select
  g.멤버                                     as 멤버번호,
  fm.name                                   as 멤버이름,
  g.대표                                     as 대표번호,
  fr.name                                   as 대표이름,
  count(d.id)                               as 고칠행,
  count(distinct d.user_id)                 as 해당계정
from 그룹 g
  left join flowers    fm on fm.id = g.멤버
  left join flowers    fr on fr.id = g.대표
  left join discoveries d  on d.flower_id = g.멤버
group by g.멤버, fm.name, g.대표, fr.name
order by g.멤버;

