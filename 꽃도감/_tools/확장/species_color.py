def resolve(name, family):
    """(색, 근거등급)을 돌려준다.

    🔴 순서를 바꾸면 안 된다. 종 → (오탐 제외) 이름 → 과.
       종 지정이 가장 정확하므로 먼저 본다.
    """
    if name in SPECIES_COLOR:
        return SPECIES_COLOR[name], '종'
    if name not in FALSE_COLOR_NAMES:
        for morph, c in NAME_COLOR:
            if morph in name:
                return c, '이름'
    from flower_art import FAMILY_COLOR
    return FAMILY_COLOR.get(family, '#E8C8D0'), '과'
